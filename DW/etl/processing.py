@contextmanager
def lock():
    p=ROOT/'.runtime/processing.lock';p.parent.mkdir(exist_ok=True)
    with p.open('a+b') as f:
        f.seek(0,2)
        if f.tell()==0:f.write(b'0');f.flush()
        f.seek(0)
        if os.name=='nt':
            import msvcrt
            msvcrt.locking(f.fileno(),msvcrt.LK_NBLCK,1)
        else:
            import fcntl
            fcntl.flock(f,fcntl.LOCK_EX|fcntl.LOCK_NB)
        try:yield
        finally:
            f.seek(0)
            if os.name=='nt':msvcrt.locking(f.fileno(),msvcrt.LK_UNLCK,1)
            else:fcntl.flock(f,fcntl.LOCK_UN)

def golden(dsn,base):
    manifest={};schema={};ddl=['CREATE SCHEMA IF NOT EXISTS dw;'];fk=[]
    with psycopg.connect(dsn,row_factory=dict_row) as c:
        c.execute('SET TRANSACTION ISOLATION LEVEL REPEATABLE READ, READ ONLY')
        tables=c.execute("SELECT table_name FROM information_schema.tables WHERE table_schema='dw' AND table_type='BASE TABLE' ORDER BY table_name").fetchall()
        for t in tables:
            name=t['table_name'];reg='dw.'+name
            columns=c.execute('''SELECT a.attname name,format_type(a.atttypid,a.atttypmod) type,a.attnotnull required,a.attidentity identity
                FROM pg_attribute a WHERE a.attrelid=%s::regclass AND a.attnum>0 AND NOT a.attisdropped ORDER BY a.attnum''',(reg,)).fetchall()
            constraints=c.execute('SELECT conname name,contype type,pg_get_constraintdef(oid) definition FROM pg_constraint WHERE conrelid=%s::regclass AND contype IN (\'p\',\'u\',\'c\',\'f\') ORDER BY conname',(reg,)).fetchall()
            schema[name]={'columns':columns,'constraints':constraints}
            quoted=lambda s:'"'+s.replace('"','""')+'"'
            colddl=[quoted(a['name'])+' '+a['type']+(' GENERATED BY DEFAULT AS IDENTITY' if a['identity'] else '')+(' NOT NULL' if a['required'] else '') for a in columns]
            colddl+=['CONSTRAINT '+quoted(v['name'])+' '+v['definition'] for v in constraints if v['type']!='f']
            ddl.append('CREATE TABLE dw.'+quoted(name)+' ('+',\n'.join(colddl)+');')
            fk+=['ALTER TABLE dw.'+quoted(name)+' ADD CONSTRAINT '+quoted(v['name'])+' '+v['definition']+';' for v in constraints if v['type']=='f']
            target=base/(name+'.csv')
            pk=c.execute('SELECT a.attname FROM pg_index i JOIN pg_attribute a ON a.attrelid=i.indrelid AND a.attnum=ANY(i.indkey) WHERE i.indrelid=%s::regclass AND i.indisprimary ORDER BY a.attnum',(reg,)).fetchall()
            with target.with_suffix('.csv.partial').open('wb') as out,c.cursor().copy(sql.SQL('COPY (SELECT * FROM dw.{} ORDER BY {}) TO STDOUT WITH (FORMAT CSV,HEADER)').format(sql.Identifier(name),sql.SQL(',').join(sql.Identifier(p['attname']) for p in pk))) as copy:
                for block in copy:out.write(block)
            target.with_suffix('.csv.partial').replace(target)
            manifest[name]={'file':target.name,'sha256':checksum(target),'rows':c.execute(sql.SQL('SELECT count(*) n FROM dw.{}').format(sql.Identifier(name))).fetchone()['n']}
    (base/'schema.sql').write_text('\n'.join(ddl+fk)+'\n',encoding='utf8');dump(base/'schema.json',schema);dump(base/'manifest.json',manifest)
    return manifest

def process(data_dir,dsn,batch_id=None,seed_silver=None):
    data_dir=Path(data_dir);preflight(data_dir);base=ROOT/'data process'
    with lock():
        for name in ['Raw','Silver','Golden']:(base/name).mkdir(parents=True,exist_ok=True)
        raw={}
        for key,(name,_,_) in SOURCES.items():
            source=data_dir/name;target=base/'Raw'/name;sha=checksum(source)
            if target.exists() and checksum(target)!=sha:
                history=base/'Raw/history';history.mkdir(exist_ok=True)
                oldsha=checksum(target);archived=history/(oldsha[:12]+'-'+name)
                if archived.exists() and checksum(archived)!=oldsha:raise RuntimeError('Raw history collision')
                if not archived.exists():shutil.copy2(target,archived)
            if not target.exists() or checksum(target)!=sha:shutil.copy2(source,target)
            if checksum(target)!=sha:raise RuntimeError('Raw bytes changed')
            raw[key]={'file':name,'sha256':sha,'bytes':target.stat().st_size}
        dump(base/'Raw/manifest.json',raw)
        report=load_postgres(data_dir,dsn,batch_id,process_dir=base,seed_silver=seed_silver)
        report['golden']=golden(dsn,base/'Golden');report['raw_unchanged']=all(checksum(data_dir/d['file'])==d['sha256'] for d in raw.values())
        report['generated_at']=datetime.now(timezone.utc).isoformat();dump(base/'manifest.json',report)
        return report
