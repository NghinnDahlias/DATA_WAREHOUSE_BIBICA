BEGIN;

CREATE TABLE IF NOT EXISTS dw.fact_order_line_candidate (
    order_line_key              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_key                   bigint NOT NULL,
    channel_key                 bigint NOT NULL,
    storefront_key              bigint NOT NULL,
    source_product_sku_key      bigint,
    warehouse_key               bigint,
    province_key                bigint,
    order_status_key            bigint,
    order_created_date_key      integer NOT NULL,
    order_created_time_key      integer,
    paid_date_key               integer,
    paid_time_key               integer,
    shipped_date_key             integer,
    shipped_time_key             integer,
    delivered_date_key           integer,
    delivered_time_key           integer,
    source_file_key              bigint NOT NULL,
    ingestion_batch_key          bigint NOT NULL,
    source_sheet_name            text NOT NULL,
    physical_row_number         integer NOT NULL,
    source_row_hash              text NOT NULL,
    quantity                     numeric(18,4),
    returned_quantity            numeric(18,4),
    unit_price_source            numeric(19,4),
    gross_item_amount_source     numeric(19,4),
    net_item_amount_source       numeric(19,4),
    seller_discount_source       numeric(19,4),
    platform_discount_source     numeric(19,4),
    shipping_buyer_charge_source numeric(19,4),
    order_amount_source          numeric(19,4),
    source_row_quality_status    text NOT NULL DEFAULT 'ACCEPTED',
    loaded_at                    timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_fact_order_line_source_row
        UNIQUE (source_file_key, source_sheet_name, physical_row_number),
    CONSTRAINT ck_fact_order_line_source_hash
        CHECK (source_row_hash ~ '^[0-9a-fA-F]{64}$'),
    CONSTRAINT ck_fact_order_line_row_number CHECK (physical_row_number > 0),
    CONSTRAINT ck_fact_order_line_quantity
        CHECK (quantity IS NULL OR quantity >= 0),
    CONSTRAINT ck_fact_order_line_returned_quantity
        CHECK (returned_quantity IS NULL OR returned_quantity >= 0),
    CONSTRAINT ck_fact_order_line_quality_status
        CHECK (source_row_quality_status IN ('ACCEPTED', 'FLAGGED', 'REJECTED_BY_CONTRACT')),
    CONSTRAINT fk_fact_order_line_order_scope
        FOREIGN KEY (order_key, channel_key, storefront_key)
        REFERENCES dw.dim_order_identity(order_key, channel_key, storefront_key),
    CONSTRAINT fk_fact_order_line_channel
        FOREIGN KEY (channel_key) REFERENCES dw.dim_channel(channel_key),
    CONSTRAINT fk_fact_order_line_storefront_scope
        FOREIGN KEY (storefront_key, channel_key)
        REFERENCES dw.dim_storefront(storefront_key, channel_key),
    CONSTRAINT fk_fact_order_line_product_scope
        FOREIGN KEY (source_product_sku_key, channel_key, storefront_key)
        REFERENCES dw.dim_source_product_sku(source_product_sku_key, channel_key, storefront_key),
    CONSTRAINT fk_fact_order_line_warehouse
        FOREIGN KEY (warehouse_key) REFERENCES dw.dim_warehouse(warehouse_key),
    CONSTRAINT fk_fact_order_line_province
        FOREIGN KEY (province_key) REFERENCES dw.dim_province(province_key),
    CONSTRAINT fk_fact_order_line_status_scope
        FOREIGN KEY (order_status_key, channel_key, storefront_key)
        REFERENCES dw.dim_order_status(order_status_key, channel_key, storefront_key),
    CONSTRAINT fk_fact_order_line_created_date
        FOREIGN KEY (order_created_date_key) REFERENCES dw.dim_date(date_key),
    CONSTRAINT fk_fact_order_line_created_time
        FOREIGN KEY (order_created_time_key) REFERENCES dw.dim_time(time_key),
    CONSTRAINT fk_fact_order_line_paid_date
        FOREIGN KEY (paid_date_key) REFERENCES dw.dim_date(date_key),
    CONSTRAINT fk_fact_order_line_paid_time
        FOREIGN KEY (paid_time_key) REFERENCES dw.dim_time(time_key),
    CONSTRAINT fk_fact_order_line_shipped_date
        FOREIGN KEY (shipped_date_key) REFERENCES dw.dim_date(date_key),
    CONSTRAINT fk_fact_order_line_shipped_time
        FOREIGN KEY (shipped_time_key) REFERENCES dw.dim_time(time_key),
    CONSTRAINT fk_fact_order_line_delivered_date
        FOREIGN KEY (delivered_date_key) REFERENCES dw.dim_date(date_key),
    CONSTRAINT fk_fact_order_line_delivered_time
        FOREIGN KEY (delivered_time_key) REFERENCES dw.dim_time(time_key),
    CONSTRAINT fk_fact_order_line_source_file
        FOREIGN KEY (source_file_key) REFERENCES dw.dim_source_file(source_file_key),
    CONSTRAINT fk_fact_order_line_batch
        FOREIGN KEY (ingestion_batch_key) REFERENCES dw.dim_ingestion_batch(ingestion_batch_key)
);

