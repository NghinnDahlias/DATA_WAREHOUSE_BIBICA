CREATE TABLE IF NOT EXISTS dw.fact_review_candidate (
    review_key              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_key               bigint,
    channel_key             bigint NOT NULL,
    storefront_key          bigint NOT NULL,
    review_date_key         integer NOT NULL,
    review_time_key         integer,
    source_file_key         bigint NOT NULL,
    ingestion_batch_key     bigint NOT NULL,
    source_sheet_name       text NOT NULL,
    physical_row_number     integer NOT NULL,
    source_row_hash         text NOT NULL,
    source_product_id       text,
    source_product_sku_key  bigint,
    star_level              smallint NOT NULL,
    has_review_text         boolean NOT NULL,
    review_text_length      integer,
    product_linkage_status  text NOT NULL DEFAULT 'UNVERIFIED',
    review_quality_status   text NOT NULL DEFAULT 'ACCEPTED',
    loaded_at               timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_fact_review_source_row
        UNIQUE (source_file_key, source_sheet_name, physical_row_number),
    CONSTRAINT ck_fact_review_source_hash
        CHECK (source_row_hash ~ '^[0-9a-fA-F]{64}$'),
    CONSTRAINT ck_fact_review_row_number CHECK (physical_row_number > 0),
    CONSTRAINT ck_fact_review_star_level CHECK (star_level BETWEEN 1 AND 5),
    CONSTRAINT ck_fact_review_text_length
        CHECK (review_text_length IS NULL OR review_text_length >= 0),
    CONSTRAINT ck_fact_review_text_presence
        CHECK ((has_review_text AND review_text_length IS NOT NULL AND review_text_length > 0)
            OR (NOT has_review_text AND (review_text_length IS NULL OR review_text_length = 0))),
    CONSTRAINT ck_fact_review_product_linkage
        CHECK (product_linkage_status IN ('UNVERIFIED', 'ORDER_ONLY', 'VALIDATED')),
    CONSTRAINT ck_fact_review_quality_status
        CHECK (review_quality_status IN ('ACCEPTED', 'FLAGGED', 'RESTRICTED')),
    CONSTRAINT fk_fact_review_order_scope
        FOREIGN KEY (order_key, channel_key, storefront_key)
        REFERENCES dw.dim_order_identity(order_key, channel_key, storefront_key),
    CONSTRAINT fk_fact_review_channel
        FOREIGN KEY (channel_key) REFERENCES dw.dim_channel(channel_key),
    CONSTRAINT fk_fact_review_storefront_scope
        FOREIGN KEY (storefront_key, channel_key)
        REFERENCES dw.dim_storefront(storefront_key, channel_key),
    CONSTRAINT fk_fact_review_date
        FOREIGN KEY (review_date_key) REFERENCES dw.dim_date(date_key),
    CONSTRAINT fk_fact_review_time
        FOREIGN KEY (review_time_key) REFERENCES dw.dim_time(time_key),
    CONSTRAINT fk_fact_review_source_file
        FOREIGN KEY (source_file_key) REFERENCES dw.dim_source_file(source_file_key),
    CONSTRAINT fk_fact_review_batch
        FOREIGN KEY (ingestion_batch_key) REFERENCES dw.dim_ingestion_batch(ingestion_batch_key),
    CONSTRAINT fk_fact_review_product_scope
        FOREIGN KEY (source_product_sku_key, channel_key, storefront_key)
        REFERENCES dw.dim_source_product_sku(source_product_sku_key, channel_key, storefront_key)
);

COMMIT;
