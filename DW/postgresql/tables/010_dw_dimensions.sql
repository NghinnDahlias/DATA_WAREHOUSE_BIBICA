BEGIN;

CREATE TABLE IF NOT EXISTS dw.dim_channel (
    channel_key   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel_code  text NOT NULL UNIQUE,
    channel_name  text NOT NULL,
    created_at    timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_dim_channel_code_nonblank CHECK (btrim(channel_code) <> ''),
    CONSTRAINT ck_dim_channel_name_nonblank CHECK (btrim(channel_name) <> '')
);

CREATE TABLE IF NOT EXISTS dw.dim_storefront (
    storefront_key   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel_key      bigint NOT NULL,
    storefront_code  text NOT NULL UNIQUE,
    storefront_name  text NOT NULL,
    product_line     text,
    created_at       timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_dim_storefront_channel_code UNIQUE (channel_key, storefront_code),
    CONSTRAINT uq_dim_storefront_key_channel UNIQUE (storefront_key, channel_key),
    CONSTRAINT ck_dim_storefront_code_nonblank CHECK (btrim(storefront_code) <> ''),
    CONSTRAINT ck_dim_storefront_name_nonblank CHECK (btrim(storefront_name) <> ''),
    CONSTRAINT fk_dim_storefront_channel
        FOREIGN KEY (channel_key) REFERENCES dw.dim_channel(channel_key)
);

CREATE TABLE IF NOT EXISTS dw.dim_order_identity (
    order_key        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel_key      bigint NOT NULL,
    storefront_key   bigint NOT NULL,
    native_order_id  text NOT NULL,
    order_namespace  text NOT NULL UNIQUE,
    created_at       timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_dim_order_identity_native
        UNIQUE (channel_key, storefront_key, native_order_id),
    CONSTRAINT uq_dim_order_identity_key_scope
        UNIQUE (order_key, channel_key, storefront_key),
    CONSTRAINT ck_dim_order_identity_native_nonblank CHECK (btrim(native_order_id) <> ''),
    CONSTRAINT ck_dim_order_identity_namespace_nonblank CHECK (btrim(order_namespace) <> ''),
    CONSTRAINT fk_dim_order_identity_channel
        FOREIGN KEY (channel_key) REFERENCES dw.dim_channel(channel_key),
    CONSTRAINT fk_dim_order_identity_storefront_scope
        FOREIGN KEY (storefront_key, channel_key)
        REFERENCES dw.dim_storefront(storefront_key, channel_key)
);

CREATE TABLE IF NOT EXISTS dw.dim_date (
    date_key       integer PRIMARY KEY,
    calendar_date  date NOT NULL UNIQUE,
    year           smallint NOT NULL,
    quarter        smallint NOT NULL,
    month          smallint NOT NULL,
    day            smallint NOT NULL,
    month_name     text NOT NULL,
    week_of_year   smallint NOT NULL,
    CONSTRAINT ck_dim_date_key_positive CHECK (date_key > 0),
    CONSTRAINT ck_dim_date_quarter CHECK (quarter BETWEEN 1 AND 4),
    CONSTRAINT ck_dim_date_month CHECK (month BETWEEN 1 AND 12),
    CONSTRAINT ck_dim_date_day CHECK (day BETWEEN 1 AND 31),
    CONSTRAINT ck_dim_date_week CHECK (week_of_year BETWEEN 1 AND 53)
);

CREATE TABLE IF NOT EXISTS dw.dim_time (
    time_key    integer PRIMARY KEY,
    native_time time NOT NULL UNIQUE,
    hour        smallint NOT NULL,
    minute      smallint NOT NULL,
    second      smallint NOT NULL,
    CONSTRAINT ck_dim_time_key_nonnegative CHECK (time_key >= 0),
    CONSTRAINT ck_dim_time_hour CHECK (hour BETWEEN 0 AND 23),
    CONSTRAINT ck_dim_time_minute CHECK (minute BETWEEN 0 AND 59),
    CONSTRAINT ck_dim_time_second CHECK (second BETWEEN 0 AND 59)
);

CREATE TABLE IF NOT EXISTS dw.dim_source_product_sku (
    source_product_sku_key  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel_key             bigint NOT NULL,
    storefront_key          bigint NOT NULL,
    native_product_id       text,
    native_sku_id           text,
    seller_sku              text,
    product_name            text,
    variation_name          text,
    product_line            text,
    conformed_product_key   text,
    mapping_status          text NOT NULL DEFAULT 'UNMAPPED',
    mapping_version         text,
    created_at              timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_dim_source_product_sku_key_scope
        UNIQUE (source_product_sku_key, channel_key, storefront_key),
    CONSTRAINT ck_dim_source_product_sku_mapping_status
        CHECK (mapping_status IN ('UNMAPPED', 'PROVISIONAL', 'VALIDATED', 'REJECTED')),
    CONSTRAINT fk_dim_source_product_sku_channel
        FOREIGN KEY (channel_key) REFERENCES dw.dim_channel(channel_key),
    CONSTRAINT fk_dim_source_product_sku_storefront_scope
        FOREIGN KEY (storefront_key, channel_key)
        REFERENCES dw.dim_storefront(storefront_key, channel_key)
);

CREATE TABLE IF NOT EXISTS dw.dim_warehouse (
    warehouse_key             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    storefront_key            bigint NOT NULL,
    native_warehouse_name     text NOT NULL,
    normalized_warehouse_name text,
    mapping_status            text NOT NULL DEFAULT 'UNMAPPED',
    mapping_version           text,
    created_at                timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_dim_warehouse_native UNIQUE (storefront_key, native_warehouse_name),
    CONSTRAINT ck_dim_warehouse_mapping_status
        CHECK (mapping_status IN ('UNMAPPED', 'PROVISIONAL', 'VALIDATED', 'REJECTED')),
    CONSTRAINT ck_dim_warehouse_name_nonblank CHECK (btrim(native_warehouse_name) <> ''),
    CONSTRAINT fk_dim_warehouse_storefront
        FOREIGN KEY (storefront_key) REFERENCES dw.dim_storefront(storefront_key)
);

CREATE TABLE IF NOT EXISTS dw.dim_province (
    province_key              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    native_province_name      text NOT NULL,
    normalized_province_name  text,
    mapping_status            text NOT NULL DEFAULT 'UNMAPPED',
    mapping_version           text,
    created_at                timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_dim_province_native UNIQUE (native_province_name),
    CONSTRAINT ck_dim_province_mapping_status
        CHECK (mapping_status IN ('UNMAPPED', 'PROVISIONAL', 'VALIDATED', 'REJECTED')),
    CONSTRAINT ck_dim_province_name_nonblank CHECK (btrim(native_province_name) <> '')
);

CREATE TABLE IF NOT EXISTS dw.dim_order_status (
    order_status_key  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel_key       bigint NOT NULL,
    storefront_key    bigint NOT NULL,
    native_status     text NOT NULL,
    reviewed_status   text,
    mapping_version   text,
    source_timezone   text,
    effective_from    date,
    effective_to      date,
    created_at        timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_dim_order_status_native_nonblank CHECK (btrim(native_status) <> ''),
    CONSTRAINT ck_dim_order_status_dates
        CHECK (effective_to IS NULL OR effective_from IS NULL OR effective_to >= effective_from),
    CONSTRAINT fk_dim_order_status_channel
        FOREIGN KEY (channel_key) REFERENCES dw.dim_channel(channel_key),
    CONSTRAINT fk_dim_order_status_storefront_scope
        FOREIGN KEY (storefront_key, channel_key)
        REFERENCES dw.dim_storefront(storefront_key, channel_key)
);

CREATE TABLE IF NOT EXISTS dw.dim_source_file (
    source_file_key   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_file_name  text NOT NULL,
    source_sha256     text NOT NULL,
    sheet_name        text NOT NULL,
    source_kind       text NOT NULL,
    source_storefront text NOT NULL,
    created_at        timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_dim_source_file_identity
        UNIQUE (source_file_name, source_sha256, sheet_name),
    CONSTRAINT ck_dim_source_file_sha256
        CHECK (source_sha256 ~ '^[0-9a-fA-F]{64}$'),
    CONSTRAINT ck_dim_source_file_kind
        CHECK (source_kind IN ('tiktok_sales', 'tiktok_reviews', 'shopee_orders')),
    CONSTRAINT ck_dim_source_file_names_nonblank
        CHECK (btrim(source_file_name) <> '' AND btrim(sheet_name) <> '' AND btrim(source_storefront) <> '')
);

CREATE TABLE IF NOT EXISTS dw.dim_ingestion_batch (
    ingestion_batch_key  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_file_key      bigint NOT NULL,
    batch_id              text NOT NULL UNIQUE,
    started_at            timestamptz NOT NULL,
    completed_at          timestamptz,
    load_status           text NOT NULL DEFAULT 'STARTED',
    row_count_read       integer,
    row_count_loaded     integer,
    created_at            timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_dim_ingestion_batch_status
        CHECK (load_status IN ('STARTED', 'LOADED', 'FAILED', 'REPLAYED')),
    CONSTRAINT ck_dim_ingestion_batch_dates
        CHECK (completed_at IS NULL OR completed_at >= started_at),
    CONSTRAINT ck_dim_ingestion_batch_counts
        CHECK ((row_count_read IS NULL OR row_count_read >= 0)
           AND (row_count_loaded IS NULL OR row_count_loaded >= 0)),
    CONSTRAINT fk_dim_ingestion_batch_source_file
        FOREIGN KEY (source_file_key) REFERENCES dw.dim_source_file(source_file_key)
);

COMMIT;
